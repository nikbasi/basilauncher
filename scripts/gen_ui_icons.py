#!/usr/bin/env python3
"""Render the launcher's UI icons from Lucide SVGs to 1-bit bitmaps.

Each icon is rasterised at the exact pixel sizes the UI draws it at, then
thresholded, so strokes land on whole pixels instead of being scaled at run
time. The layout matches src/ui_font.h: column-major, (h + 7) / 8 bytes per
column, bit 7 of a column's first byte is the top row, a set bit is ink.

Usage (needs Pillow and cairosvg, and the lucide-static package):
    npm pack lucide-static@0.460.0 && tar xzf lucide-static-0.460.0.tgz
    python3 scripts/gen_ui_icons.py package/icons > src/ui_icons.h
"""

import io
import re
import sys
from pathlib import Path

import cairosvg
from PIL import Image

# (C name, Lucide icon, sizes in px). Sizes are the ones ui.cpp draws.
ICONS = [
    ("Back", "arrow-left", [28]),
    ("Chevron", "chevron-right", [24]),
    ("Up", "arrow-up", [24]),
    ("Folder", "folder", [24, 28]),
    ("File", "file", [28]),
    ("FileText", "file-text", [28]),
    ("Image", "image", [28]),
    ("Chip", "cpu", [28]),
    ("Paste", "clipboard-paste", [24, 40]),
    ("More", "ellipsis-vertical", [24]),
    ("Select", "list-checks", [24]),
    ("FolderPlus", "folder-plus", [24, 40]),
    ("FilePlus", "file-plus", [40]),
    ("Copy", "copy", [40]),
    ("Cut", "scissors", [40]),
    ("Rename", "pencil", [24, 40]),
    ("Trash", "trash-2", [24, 40]),
    ("Transfer", "arrow-down-up", [36]),
    ("Wifi", "wifi", [20, 36]),
    ("Gps", "locate-fixed", [36]),
    ("Settings", "settings", [24, 36]),
    ("Bolt", "zap", [20]),
    ("Lock", "lock", [20]),
    ("Check", "check", [24]),
    ("Play", "play", [28]),
    ("Update", "circle-arrow-up", [20, 24]),
    ("Plus", "plus", [24]),
    ("Refresh", "refresh-cw", [24]),
    ("Globe", "globe", [24]),
    ("Clock", "clock", [24]),
    ("Info", "info", [24]),
    ("Moon", "moon", [24]),
    ("Alert", "triangle-alert", [40]),
    ("Square", "square", [24]),
    ("SquareCheck", "square-check", [24]),
]

# Lucide draws 2-unit strokes on a 24-unit grid. A little heavier keeps every
# stroke at least two pixels wide on 1-bit e-ink at the smaller sizes.
STROKE = {20: 2.4, 24: 2.25, 28: 2.1}
THRESHOLD = 140  # luminance below this counts as ink


def render(svg_text, px):
    stroke = STROKE.get(px, 2.0)
    svg = re.sub(r'stroke-width="[^"]*"', f'stroke-width="{stroke}"', svg_text, count=1)
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=px, output_height=px)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.alpha_composite(img)
    gray = bg.convert("L")
    stride = (px + 7) // 8
    data = bytearray()
    pix = gray.load()
    for x in range(px):
        col = bytearray(stride)
        for y in range(px):
            if pix[x, y] < THRESHOLD:
                col[y >> 3] |= 0x80 >> (y & 7)
        data.extend(col)
    return bytes(data)


def main():
    icon_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "package/icons")
    out = [
        "#pragma once",
        "",
        "// GENERATED by scripts/gen_ui_icons.py -- do not edit by hand.",
        "//",
        "// Lucide icons (https://lucide.dev), ISC License, Copyright (c) Lucide",
        "// Contributors 2022 and Cole Bemis 2013-2022 (Feather, MIT); see",
        "// fonts/Lucide-LICENSE.txt. Rendered to 1-bit at each size the UI uses.",
        "//",
        "// Column-major like ui_font.h: (h + 7) / 8 bytes per column, bit 7 of a",
        "// column's first byte is the top row, and a set bit is ink.",
        "",
        "#include <Arduino.h>",
        "",
        "struct UiIcon {",
        "  uint8_t w;",
        "  uint8_t h;",
        "  const uint8_t* bits;",
        "};",
        "",
    ]
    total = 0
    for name, lucide, sizes in ICONS:
        svg_text = (icon_dir / f"{lucide}.svg").read_text()
        for px in sizes:
            data = render(svg_text, px)
            total += len(data)
            out.append(f"// {lucide} {px}px")
            out.append(f"static const uint8_t kIcon{name}{px}Bits[] PROGMEM = {{")
            for i in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
            out.append("};")
            out.append(f"static constexpr UiIcon kIcon{name}{px} = {{{px}, {px}, kIcon{name}{px}Bits}};")
            out.append("")
    sys.stdout.write("\n".join(out))
    sys.stderr.write(f"{total} bytes of icon data\n")


if __name__ == "__main__":
    main()
